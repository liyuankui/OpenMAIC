import fs from 'node:fs';
import path from 'node:path';

const TEMPLATES_DIR = 'lib/generation/prompts/templates';
const SNIPPETS_DIR = 'lib/generation/prompts/snippets';
const OUTPUT = 'lib/generation/prompts/bundled-prompts.ts';

function esc(s) {
  return s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$/g, '\\$');
}

const prompts = {};
for (const dir of fs.readdirSync(TEMPLATES_DIR)) {
  const dirPath = path.join(TEMPLATES_DIR, dir);
  if (!fs.statSync(dirPath).isDirectory()) continue;
  const entry = {};
  for (const file of ['system.md', 'user.md']) {
    const fp = path.join(dirPath, file);
    if (fs.existsSync(fp)) entry[file === 'system.md' ? 'system' : 'user'] = fs.readFileSync(fp, 'utf-8').trim();
  }
  if (entry.system) prompts[dir] = entry;
}

const snippets = {};
for (const file of fs.readdirSync(SNIPPETS_DIR)) {
  if (!file.endsWith('.md')) continue;
  const id = file.replace('.md', '');
  snippets[id] = fs.readFileSync(path.join(SNIPPETS_DIR, file), 'utf-8').trim();
}

const lines = [
  '// Auto-generated by scripts/cf-bundle-prompts.mjs — DO NOT EDIT',
  'export const bundledPrompts: Record<string, { system: string; user: string }> = {',
];
for (const [id, p] of Object.entries(prompts)) {
  lines.push(`  '${id}': {`);
  lines.push(`    system: \`${esc(p.system)}\`,`);
  lines.push(`    user: \`${esc(p.user || '')}\`,`);
  lines.push(`  },`);
}
lines.push('};');
lines.push('');
lines.push('export const bundledSnippets: Record<string, string> = {');
for (const [id, s] of Object.entries(snippets)) {
  lines.push(`  '${id}': \`${esc(s)}\`,`);
}
lines.push('};');
lines.push('');

fs.writeFileSync(OUTPUT, lines.join('\n'));
console.log(`[cf-bundle-prompts] Bundled ${Object.keys(prompts).length} prompts, ${Object.keys(snippets).length} snippets`);
